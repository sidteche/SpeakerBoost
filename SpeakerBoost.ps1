<#
SpeakerBoost.ps1 - a lightweight DTS:X Ultra replacement for the laptop's built-in speakers.

It writes an Equalizer APO config that applies ONLY to the internal "Speakers (Realtek)"
output. Wired headphones (a separate "Headphones" device), Bluetooth audio and HDMI
monitors are never touched.

Needs:
  - Equalizer APO   https://sourceforge.net/projects/equalizerapo/
                    (during install, tick ONLY "Speakers - Realtek(R) Audio")
  - LoudMax (optional but recommended, free limiter) https://loudmax.blogspot.com/
                    put LoudMax64.dll in "C:\Program Files\VSTPlugins\"

Usage (PowerShell as Administrator):
  .\SpeakerBoost.ps1            # apply boost (default level: Medium)
  .\SpeakerBoost.ps1 -Level High
  .\SpeakerBoost.ps1 -Off       # turn boost off
#>
param(
    [ValidateSet('Low', 'Medium', 'High')]
    [string]$Level = 'Medium',
    [switch]$Off
)

$ErrorActionPreference = 'Stop'
$apoDir     = 'C:\Program Files\EqualizerAPO'
$configFile = Join-Path $apoDir 'config\config.txt'

if (-not (Test-Path $apoDir)) {
    Write-Host 'Equalizer APO is not installed. Install it first (see top of this script).' -ForegroundColor Red
    exit 1
}

# Find the built-in Realtek speakers endpoint, so we target it by its unique ID.
$render = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\MMDevices\Audio\Render'
$speaker = Get-ChildItem $render | Where-Object {
    $p = Get-ItemProperty "$($_.PSPath)\Properties" -ErrorAction SilentlyContinue
    $p.'{a45c254e-df1c-4efd-8020-67d146a850e0},2' -eq 'Speakers' -and
    $p.'{b3f8fa53-0004-438e-9003-51a46e139bfc},6' -like 'Realtek*'
} | Select-Object -First 1

if (-not $speaker) {
    Write-Host 'Could not find the built-in Realtek Speakers device.' -ForegroundColor Red
    exit 1
}
$guid = $speaker.PSChildName
Write-Host "Built-in speakers: $guid"

# Back up whatever config exists the first time we run.
$backup = "$configFile.before-speakerboost"
if ((Test-Path $configFile) -and -not (Test-Path $backup)) {
    Copy-Item $configFile $backup
}

if ($Off) {
    Set-Content -Path $configFile -Encoding UTF8 -Value '# SpeakerBoost off'
    Write-Host 'Speaker boost turned OFF.' -ForegroundColor Yellow
    exit 0
}

# Look for the LoudMax limiter, which lets us push volume without clipping.
$loudMax = @(
    'C:\Program Files\VSTPlugins\LoudMax64.dll',
    'C:\Program Files\Steinberg\VSTPlugins\LoudMax64.dll',
    'C:\Program Files\Common Files\VST2\LoudMax64.dll',
    "$apoDir\VSTPlugins\LoudMax64.dll"
) | Where-Object { Test-Path $_ } | Select-Object -First 1

# Preamp gain in dB. Without a limiter, keep it low so loud parts don't crackle.
$gain = if ($loudMax) { @{ Low = 4; Medium = 7; High = 10 }[$Level] }
        else          { @{ Low = 0; Medium = 2; High = 3 }[$Level] }

$lines = @(
    '# Generated by SpeakerBoost.ps1 - applies to built-in speakers only'
    "Device: $guid"
    ''
    "Preamp: $gain dB"
    '# Tiny speakers cannot play deep bass; cutting it frees headroom for volume'
    'Filter: ON HPQ Fc 150 Hz Q 0.707'
    '# Reduce boxy/muddy sound'
    'Filter: ON PK Fc 300 Hz Gain -2 dB Q 1.0'
    '# Boost voices and the range ears hear best (sounds louder, clearer dialog)'
    'Filter: ON PK Fc 2500 Hz Gain 4 dB Q 0.9'
    '# A little air and detail'
    'Filter: ON HS Fc 8000 Hz Gain 2 dB'
)

if ($loudMax) {
    $lines += ''
    $lines += '# Brickwall limiter: keeps everything below 0 dB so nothing clips'
    $lines += "VSTPlugin: Library `"$loudMax`""
} else {
    Write-Host 'LoudMax not found - using a safe, lower boost. Install LoudMax for more volume.' -ForegroundColor Yellow
}

Set-Content -Path $configFile -Encoding UTF8 -Value $lines
Write-Host "Speaker boost ON (level: $Level, preamp +$gain dB)." -ForegroundColor Green
